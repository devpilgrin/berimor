//! Контракт Mediation.
//!
//! Источник: `docs/arch/mediation.md` §3. Схема — часть типа (derive), а не
//! отдельный артефакт, который можно забыть синхронизировать вручную
//! (см. ADR-0020, аргумент про усиление инварианта I3 компилятором).
//! ROADMAP: M1.

use serde::{de::DeserializeOwned, Serialize};

/// Реализуется для каждого типа данных, которым модель обязана ответить
/// на структурированном шаге. `#[serde(deny_unknown_fields)]` на
/// конкретной реализации — обязательное условие (mediation.md §4.2):
/// поле сверх контракта — отказ, а не тихо проигнорированное значение.
pub trait Contract: Serialize + DeserializeOwned + Send + Sync + 'static {
    /// Версия схемы — пишется в патч состояния вместе с результатом (mediation.md §4.4).
    const SCHEMA_VERSION: u32;
    /// Имя контракта — используется в подсказке модели и в телеметрии отказов.
    const NAME: &'static str;
}
