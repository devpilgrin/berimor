/**
 * Верификация подписи артефакта уже доверенным нативным бинарником.
 *
 * Источник: docs/arch/deployment.md §9, ADR-0025 — bootstrap не реализует
 * криптографическую проверку сам, а вызывает подкоманду `berimor verify`
 * уже доверенного нативного бинарника, а не переизобретает её на другом
 * языке (риск расхождения двух независимых реализаций одной проверки).
 *
 * Не используется на первой установке (см. checksums-manifest.ts): на первом
 * запуске ещё нет доверенного нативного бинарника, который мог бы проверить
 * сам себя — вызов этой функции над только что скачанным, ещё не
 * верифицированным бинарником циркулярен (поддельный бинарник соврёт на
 * собственный `verify`). Первая установка верифицируется отдельно, по
 * SHA-256, пришпиленному в сам npm-пакет (ROADMAP D3, checksum.ts). Эта
 * функция — задел для D4 (само-обновление): там уже есть предыдущий
 * доверенный бинарник, который проверяет новый, — не циркулярно.
 */
import { spawnSync } from "node:child_process";

export function verifyArtifact(nativeBinaryPath: string, artifactPath: string): boolean {
  const result = spawnSync(nativeBinaryPath, ["verify", artifactPath], {
    stdio: "inherit",
  });
  return result.status === 0;
}
